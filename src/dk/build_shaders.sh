#!/bin/sh
# Rebuilds dk_shaders.inc from the *.glsl here with devkitPro's `uam` (run where devkitpro is installed, e.g. the build container):
#   sh src/dk/build_shaders.sh   (needs python3 for the C array)
set -e
cd "$(dirname "$0")"
OUT=dk_shaders.inc
echo "// Generated by build_shaders.sh from the *.glsl in this folder (uam): the deko3d backend's shader modules (.dksh)." > $OUT
for s in quad_vsh:vert quad_fsh:frag gui_vsh:vert gui_fsh:frag; do
  n=${s%:*}; t=${s#*:}
  uam -s $t -o /tmp/$n.dksh $n.glsl
  python3 - "$n" /tmp/$n.dksh >> $OUT <<'PY'
import sys
n, p = sys.argv[1], sys.argv[2]
d = open(p, 'rb').read()
print("alignas(8) static const unsigned char dkshader_%s[%d] = {" % (n, len(d)))
for i in range(0, len(d), 16):
    print("  " + ",".join("0x%02x" % b for b in d[i:i+16]) + ",")
print("};")
PY
done
